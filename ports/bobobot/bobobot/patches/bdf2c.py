#!/usr/bin/env python3
"""Convert the X misc-fixed 6x13.bdf into a C header with glyphs 0-255 (one byte per row, MSB = left)."""
import sys

ASCENT, HEIGHT, WIDTH = 11, 13, 6

def main(src, dst):
    glyphs = {}
    enc = bbx = rows = None
    with open(src, encoding="latin-1") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "ENCODING":
                enc = int(p[1])
            elif p[0] == "BBX":
                bbx = [int(v) for v in p[1:5]]
            elif p[0] == "BITMAP":
                rows = []
            elif p[0] == "ENDCHAR":
                if 0 <= enc <= 255:
                    w, h, xo, yo = bbx
                    cell = [0] * HEIGHT
                    top = ASCENT - (yo + h)
                    for i, r in enumerate(rows):
                        y = top + i
                        if 0 <= y < HEIGHT:
                            v = int(r, 16) << (8 - len(r) * 4) if len(r) < 2 else int(r[:2], 16)
                            cell[y] = (v >> xo) & 0xFC if xo >= 0 else (v << -xo) & 0xFC
                    glyphs[enc] = cell
                rows = None
            elif rows is not None:
                rows.append(p[0])
    with open(dst, "w") as o:
        o.write("/* Generated by bdf2c.py from xorg font-misc-misc 6x13.bdf (public domain). */\n")
        o.write("static const unsigned char font6x13[256][13] = {\n")
        for c in range(256):
            cell = glyphs.get(c, [0] * HEIGHT)
            o.write("  {" + ",".join("0x%02x" % v for v in cell) + "},\n")
        o.write("};\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
