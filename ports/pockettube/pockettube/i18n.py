def set_lang(lang):
    global LANG
    LANG = lang if lang in LANGS else "en"


def T(key, **kw):
    pair = STRINGS.get(key)
    if pair is None:
        return key
    s = pair[LANGS.index(LANG)]
    return s.format(**kw) if kw else s


def decimal(x):
    s = f"{x:.1f}"
    return s.replace(".", ",") if LANG in DECIMAL_COMMA else s
