-- Tiny 3x5 bitmap font, built at runtime so the game needs no font files.
local G = {
  A="010101111101101", B="110101110101110", C="011100100100011", D="110101101101110",
  E="111100110100111", F="111100110100100", G="011100101101011", H="101101111101101",
  I="111010010010111", J="001001001101010", K="101101110101101", L="100100100100111",
  M="101111111101101", N="110101101101101", O="010101101101010", P="110101110100100",
  Q="010101101110011", R="110101110101101", S="011100010001110", T="111010010010010",
  U="101101101101111", V="101101101101010", W="101101111111101", X="101101010101101",
  Y="101101010010010", Z="111001010100111",
  ["0"]="111101101101111", ["1"]="010110010010111", ["2"]="110001010100111",
  ["3"]="110001010001110", ["4"]="101101111001001", ["5"]="111100110001110",
  ["6"]="011100111101111", ["7"]="111001010010010", ["8"]="111101111101111",
  ["9"]="111101111001110",
  [" "]="000000000000000", ["."]="000000000000010", [","]="000000000010100",
  ["!"]="010010010000010", ["?"]="110001010000010", [":"]="000010000010000",
  ["-"]="000000111000000", ["+"]="000010111010000", ["/"]="001001010100100",
  ["'"]="010010000000000", ["("]="001010010010001", [")"]="100010010010100",
  ["%"]="101001010100101", [">"]="100010001010100", ["<"]="001010100010001",
  ["*"]="000101010101000", ["="]="000111000111000",
}

local order = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,!?:-+/'()%><*="

return function()
  local n = #order
  local img = love.image.newImageData(1 + n * 4, 5)
  for x = 0, img:getWidth() - 1 do
    for y = 0, 4 do img:setPixel(x, y, 0, 0, 0, 0) end
  end
  local x = 0
  for i = 1, n do
    local c = order:sub(i, i)
    for y = 0, 4 do img:setPixel(x, y, 1, 0, 1, 1) end -- separator
    local bits = G[c]
    for r = 0, 4 do
      for col = 0, 2 do
        if bits:sub(r * 3 + col + 1, r * 3 + col + 1) == "1" then
          img:setPixel(x + 1 + col, r, 1, 1, 1, 1)
        end
      end
    end
    x = x + 4
  end
  for y = 0, 4 do img:setPixel(x, y, 1, 0, 1, 1) end
  local f = love.graphics.newImageFont(img, order, 1)
  f:setLineHeight(7 / 5)
  return f
end
